"""台股標的類型分類（目前只處理「是不是權證」）。

為什麼要有這個模組：
    使用者不交易權證，且權證會嚴重污染系統——實測 2026-07-15 當日 367 筆台股價格中
    **300 筆是權證（81.7%）**，使得「漲跌家數」實際上是權證統計；同步 fan-out 也因此
    多跑兩萬多個無意義的任務（權證無財報：實測 6 碼代號有財報者 0 檔）。

**為什麼用代號區間而非名稱**（這是踩過坑後的結論）：
    先前用「名稱含 購/售」判斷，兩個方向都會錯：
      - 漏判：牛證/熊證名稱是「牛」「熊」不含購售 → 26 檔漏網，搜「台積電」會跑出
        `03726B 台積電富邦64熊01` 混在 `2330 台積電` 旁邊。
      - 誤判：`2945 三商家購`、`3085 新零售` 是**真公司**，名字剛好含購/售，
        只靠「6 碼」這個護欄才沒被誤殺——等於把正確性押在巧合上。
    代號區間是主管機關定義的結構，穩定且無歧義。

6 碼代號分群（實測全庫）：
    00 → ETF（含 00400A 主動式 ETF）    01 → REIT（01001T 土銀富邦R1）
    02 → ETN（020000 富邦特選蘋果N）    28 → 特別股（2887Z1 台新新光己特）
    91 → 存託憑證 DR（910322 康師傅-DR）
    03~08、70~73 → **權證**（上市 03~08、上櫃 70~73）
"""

from __future__ import annotations

#: 6 碼權證代號的前兩碼。上市 03~08、上櫃 70~73。
#: 刻意不含 00(ETF)/01(REIT)/02(ETN)/28(特別股)/91(DR)——那些都是使用者要留的標的。
TW_WARRANT_SYMBOL_PREFIXES: frozenset[str] = frozenset(
    {"03", "04", "05", "06", "07", "08", "70", "71", "72", "73"}
)


def is_tw_warrant(symbol: str | None) -> bool:
    """是否為台股權證（認購/認售/牛證/熊證）。

    :param symbol: 股票代號
    :return: True 表示權證 —— 呼叫端應將其 is_active=False，不納入同步與統計

    僅依代號結構判斷，不看名稱（見模組 docstring）。非 6 碼一律 False，
    故 4 碼的 `2945 三商家購` 這類真公司不會被誤判。
    """
    if not symbol or len(symbol) != 6:
        return False
    return symbol[:2] in TW_WARRANT_SYMBOL_PREFIXES


#: 給 SQL 用的等價條件（回填/停用腳本要在 DB 端判定）。必須與 is_tw_warrant 同義。
SQL_IS_TW_WARRANT = (
    "(length(symbol) = 6 AND left(symbol, 2) IN "
    "('03','04','05','06','07','08','70','71','72','73'))"
)


__all__ = ["SQL_IS_TW_WARRANT", "TW_WARRANT_SYMBOL_PREFIXES", "is_tw_warrant"]
